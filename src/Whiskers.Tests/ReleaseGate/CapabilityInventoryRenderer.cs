using System.Text;
using Whiskers.Services.Mutations;

namespace Whiskers.Tests.ReleaseGate;

/// <summary>
/// Renders docs/v1/CAPABILITY_INVENTORY.md (contract 0008, D7): one row per capability of the catalog, joined with
/// its verification contract, the surfaces <c>MutationGatewayCoverageTests.Inventory</c> pins, its compositions and
/// the §7 rows that name it. Generated — the snapshot test compares it and writes <c>.actual</c> on a difference.
/// </summary>
public static class CapabilityInventoryRenderer
{
    public static string Render(ICapabilityCatalog catalog, IReadOnlyList<PathRow> rows)
        => Render(catalog, rows, MutationGatewayCoverageTests.Inventory, MutationCompositions.Entries);

    public static string Render(ICapabilityCatalog catalog, IReadOnlyList<PathRow> rows,
        IReadOnlyList<(string Surface, string Capability, string Boundary)> surfaces,
        IReadOnlyList<(string Outer, IReadOnlyList<string> Inner)> compositions)
    {
        var sb = new StringBuilder();
        sb.Append("# Capability inventory\n\n");
        sb.Append("<!-- generated by ReleaseGateTests.The_capability_inventory_matches_the_code — do not edit -->\n\n");
        sb.Append("Generated — do not edit. One row per capability of `CapabilityCatalog`, sorted by id, joined with its\n");
        sb.Append("verification contract (`VerificationContracts`), the surfaces pinned by `MutationGatewayCoverageTests.Inventory`,\n");
        sb.Append("its compositions (`MutationCompositions`) and the rows of [`PRODUCT_CONTRACT.md` §7](PRODUCT_CONTRACT.md#7-path-matrix-current-state)\n");
        sb.Append("that name it (M rows through their tool, the others through [`PATH_CAPABILITIES.md`](PATH_CAPABILITIES.md)).\n");
        sb.Append("Contract 0008, D7: §7 stays hand-written; this file is generated and the release gate joins the two (R12–R15).\n\n");

        var all = catalog.All.OrderBy(c => c.Id, StringComparer.Ordinal).ToList();
        var levels = all.GroupBy(c => c.RequiredLevel).OrderBy(g => g.Key, StringComparer.Ordinal).Select(g => $"{g.Key} {g.Count()}");
        sb.Append($"{all.Count} capabilities, {all.Count(c => c.McpTool is not null)} of them with an MCP tool; by level: {string.Join(", ", levels)}.\n\n");

        sb.Append("| Capability | Level | Target | Risk | MCP tool | Verification | Surfaces | Composes | Composed by | §7 rows |\n");
        sb.Append("|---|---|---|---|---|---|---|---|---|---|\n");
        foreach (var c in all)
        {
            var verification = VerificationContracts.Find(c.Id) is { } v
                ? (v.Kind == VerificationKind.ReadBack ? "read back: " : "`NotVerifiable`: ") + v.Reason
                : "— (no contract: recorded as not verifiable)";
            var onSurfaces = surfaces.Where(s => s.Capability.Split(',', StringSplitOptions.TrimEntries).Contains(c.Id))
                .Select(s => s.Surface).Distinct().OrderBy(s => s, StringComparer.Ordinal);
            var composes = compositions.Where(e => e.Outer == c.Id).SelectMany(e => e.Inner).Distinct().OrderBy(s => s, StringComparer.Ordinal);
            var composedBy = compositions.Where(e => e.Inner.Contains(c.Id)).Select(e => e.Outer).Distinct().OrderBy(s => s, StringComparer.Ordinal);
            var named = rows.Where(r => r.McpTool is not null ? r.McpTool == c.McpTool : r.Capabilities.Contains(c.Id))
                .Select(r => r.Id).Distinct().OrderBy(RowOrder).ThenBy(r => r, StringComparer.Ordinal);
            sb.Append("| `").Append(c.Id).Append("` | ").Append(c.RequiredLevel).Append(" | ").Append(c.TargetKind)
              .Append(" | ").Append(c.Risk).Append(" | ").Append(c.McpTool is null ? "—" : $"`{c.McpTool}`")
              .Append(" | ").Append(Cell(verification))
              .Append(" | ").Append(List(onSurfaces)).Append(" | ").Append(List(composes, code: true))
              .Append(" | ").Append(List(composedBy, code: true)).Append(" | ").Append(List(named)).Append(" |\n");
        }
        return sb.ToString();
    }

    private static string RowOrder(string id) => id[..1] switch { "M" => "1", "A" => "2", "S" => "3", "T" => "4", _ => "5" }
                                                 + int.Parse(id[2..]).ToString("D4");

    private static string List(IEnumerable<string> items, bool code = false)
    {
        var list = items.Select(i => code ? $"`{i}`" : i).ToList();
        return list.Count == 0 ? "—" : string.Join(", ", list);
    }

    private static string Cell(string text) => text.Replace("|", "\\|").Replace("\n", " ");
}
